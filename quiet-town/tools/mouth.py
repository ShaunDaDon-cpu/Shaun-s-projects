"""Mouth movement from the voiceover: per-frame mouth openness (0 closed, 1 small, 2 open) for each line.

    python tools/mouth.py        # reads out/vo/NN.wav, writes src/vo-mouth.js

Finds syllable peaks in the smoothed loudness (at least GAP frames apart), opens the mouth around
each peak, keeps it half-open between peaks while there is sound, and closes it in silence. That
paces the mouth to the words instead of fluttering with every frame of the waveform.
"""
import glob, json, os
import numpy as np
import soundfile as sf

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FPS, GAP, OPEN = 60, 10, 7          # peaks at least 10 frames (~0.17 s) apart; mouth fully open ~7 frames each

out = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'out', 'vo', '*.wav'))):
    y, sr = sf.read(f, dtype='float32')
    if y.ndim > 1: y = y.mean(1)
    hop = sr // FPS
    rms = np.array([np.sqrt(np.mean(y[i:i + hop * 2] ** 2)) for i in range(0, len(y), hop)])
    rms = np.convolve(rms, np.ones(5) / 5, mode='same')                 # smooth ~80 ms
    ref = np.percentile(rms[rms > 1e-4], 90) if np.any(rms > 1e-4) else 1
    lv = rms / ref
    voiced = lv > .15
    # syllable peaks: local maxima above a floor, greedily kept from loudest down, GAP frames apart
    cand = [i for i in range(1, len(lv) - 1) if lv[i] >= lv[i - 1] and lv[i] >= lv[i + 1] and lv[i] > .3]
    peaks = []
    for i in sorted(cand, key=lambda i: -lv[i]):
        if all(abs(i - p) >= GAP for p in peaks): peaks.append(i)
    m = np.where(voiced, 1, 0)
    for p in peaks:
        a, b = max(0, p - OPEN // 2), min(len(m), p + OPEN // 2 + 1)
        m[a:b] = 2
    out[int(os.path.basename(f)[:2])] = ''.join(map(str, m))

with open(os.path.join(ROOT, 'src', 'vo-mouth.js'), 'w') as fh:
    fh.write('// Generated by tools/mouth.py: line -> mouth openness per frame at 60 fps from the start of its voice (0 closed, 1 small, 2 open)\n')
    fh.write('export const MOUTH = ' + json.dumps(out) + ';\n')
print('lines:', len(out))
