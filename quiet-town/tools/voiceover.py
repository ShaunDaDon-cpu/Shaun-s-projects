"""Voiceover for The Quiet Town, made with Kokoro (open-weight TTS, Apache-2.0), run locally.

    python tools/voiceover.py <kokoro-v1.0.onnx> <voices-v1.0.bin>

Reads out/lines.json (exported from src/script.js), casts each line, fits it into its shot,
writes out/vo/NN.wav, the full track out/vo.wav, and src/vo-timing.js (offset + length of each
line, which the captions use to pop words in time with the speech).
"""
import json, os, subprocess, sys, tempfile
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'out')
SR = 48000

# who -> (voice, pitch in semitones, formant handling, base speed)
CAST = {
    '':        ('af_heart', 1, 'shifted', 1.12),    # the kid, "Foghorn": a boy voiced the cartoon way, by a bright higher voice
    'ME':      ('af_heart', 1, 'shifted', 1.0),
    'MOM':     ('af_nicole', 0, 'preserved', 1.0),  # naturally soft and breathy
    'DAD':     ('am_michael', 0, 'preserved', 1.0),
    'MAYOR':   ('bm_george', -1, 'preserved', 1.0),
    'GRANDMA': ('bf_emma', -2, 'preserved', .95),
}
SAY = {  # spoken text where it differs from the caption
    15: "Grandma hasn't said a word since nineteen seventy-six.",
    27: 'The dam is breaking!',
    43: 'Pay it yourself, Gerald!',
}
WHISPER = {13, 19, 36, 49}
SHOUT = {27, 43}
LEAD, GAP, SPILL = .05, .06, .22      # start after the cut, gap between lines, allowed run-over into the next shot


def fx(n, semis, formant):
    f = []
    if semis:
        f.append(f'rubberband=pitch={2 ** (semis / 12):.5f}:formant={formant}')
    if n in WHISPER:
        f += ['highpass=f=320', 'equalizer=f=5500:t=q:w=1:g=5', 'volume=0.55']
    elif n in SHOUT:
        f += ['highpass=f=120', 'equalizer=f=2600:t=q:w=1:g=6', 'volume=3.2', 'asoftclip=type=tanh', 'volume=0.8']
    else:
        f += ['highpass=f=80', 'equalizer=f=3000:t=q:w=1.2:g=2', 'acompressor=threshold=0.1:ratio=3:attack=5:release=80']
    f.append(f'aresample={SR}')
    return ','.join(f)


def trim(x, thr=.012, pad=.03, sr=24000):
    idx = np.where(np.abs(x) > thr)[0]
    if not len(idx):
        return x
    a, b = max(0, idx[0] - int(pad * sr)), min(len(x), idx[-1] + int(pad * sr))
    return x[a:b]


def ffmpeg_fx(x, sr, chain, tempo=1.0):
    if tempo > 1.001:
        chain = f'atempo={tempo:.4f},' + chain
    with tempfile.TemporaryDirectory() as d:
        i, o = os.path.join(d, 'i.wav'), os.path.join(d, 'o.wav')
        sf.write(i, x, sr)
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', i, '-af', chain, '-ac', '1', o], check=True)
        y, _ = sf.read(o, dtype='float32')
    return y


def main(model, voices):
    k = Kokoro(model, voices)
    lines = [l for l in json.load(open(os.path.join(OUT, 'lines.json'))) if l['text']]
    total = max(l['start'] + l['dur'] for l in json.load(open(os.path.join(OUT, 'lines.json'))))
    os.makedirs(os.path.join(OUT, 'vo'), exist_ok=True)
    track = np.zeros(int(total * SR) + SR, dtype=np.float32)
    timing, prev_end = {}, 0.0
    for i, l in enumerate(lines):
        n, who = l['n'], l['who']
        voice, semis, formant, speed = CAST.get(who, CAST[''])
        text = SAY.get(n, l['text'])
        start = max(l['start'] + LEAD, prev_end + GAP)
        limit = l['start'] + l['dur'] + (SPILL if i < len(lines) - 1 else .8)
        avail = limit - start
        y = None
        for _ in range(4):                         # speed up until it fits the shot
            x, sr = k.create(text, voice=voice, speed=speed, lang='en-us')
            x = trim(np.asarray(x, dtype=np.float32), sr=sr)
            ln = len(x) / sr
            if ln <= avail or speed >= 1.45:
                break
            speed = min(1.45, speed * ln / avail * 1.02)
        tempo = max(1.0, (len(x) / sr) / avail)    # last resort: time-stretch
        y = ffmpeg_fx(x, sr, fx(n, semis, formant), tempo)
        ln = len(y) / SR
        s0 = int(start * SR)
        track[s0:s0 + len(y)] += y[:len(track) - s0]
        sf.write(os.path.join(OUT, 'vo', f'{n:02d}.wav'), y, SR)
        timing[n] = [round(start - l['start'], 3), round(ln, 3)]
        prev_end = start + ln
        flag = '  (stretched x%.2f)' % tempo if tempo > 1.001 else ''
        print(f'{n:2d} {voice:10s} speed {speed:.2f}  {start:6.2f}-{prev_end:6.2f}s  shot ends {l["start"] + l["dur"]:6.2f}{flag}  {text}')
    peak = np.max(np.abs(track)) or 1
    track = track / peak * .9
    sf.write(os.path.join(OUT, 'vo.wav'), np.stack([track, track], 1), SR)
    with open(os.path.join(ROOT, 'src', 'vo-timing.js'), 'w') as f:
        f.write('// Generated by tools/voiceover.py: line number -> [seconds after the cut the voice starts, seconds it lasts]\n')
        f.write('export const VO = ' + json.dumps(timing) + ';\n')
    print('vo ->', os.path.join(OUT, 'vo.wav'))


if __name__ == '__main__':
    main(*sys.argv[1:3])
